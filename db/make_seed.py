def sql(v):
    if v is None:
        return "NULL"
    if isinstance(v, (int, float, Decimal)):
        return str(v)
    return "'" + str(v).replace("'", "''") + "'"


def row(table, cols, values):
    return f"INSERT INTO {table} ({', '.join(cols)}) VALUES ({', '.join(sql(v) for v in values)});"


def pbkdf2(password, label):
    salt = hashlib.sha256(("abc-shop-seed-" + label).encode()).digest()[:16]
    digest = hashlib.pbkdf2_hmac("sha256", password.encode(), salt, 120_000, 32)
    return f"pbkdf2$120000${base64.b64encode(salt).decode()}${base64.b64encode(digest).decode()}"


def totals(lines, rate):
    subtotal = sum(q * p for _, _, q, p in lines)
    discount = int((Decimal(subtotal) * Decimal(rate)).quantize(Decimal(1), ROUND_HALF_UP))
    fee = 0 if subtotal - discount >= FREE_FROM else SHIPPING_FEE
    return subtotal, discount, fee, subtotal - discount + fee


def main():
    source = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else HERE / "seed" / "products.json"
    products = json.loads(source.read_text(encoding="utf-8"))
    slug_to_cat = {c[3]: c for c in CATEGORIES}
    out = ["-- Generated by db/make_seed.py from db/seed/products.json. Demo password of every account: " + PASSWORD]
    for c in CATEGORIES:
        out.append(row("category", ["category_id", "parent_id", "name", "slug", "detail_kind"], c))
    by_cat = {}
    for pid, p in enumerate(products, start=1):
        cat = slug_to_cat[p["category_slug"]]
        out.append(row("product", ["product_id", "category_id", "sku", "name", "brand", "price", "stock_quantity",
                                   "description", "image_file", "status", "created_at"],
                       [pid, cat[0], p["sku"], p["name"], p.get("brand"), p["price"], p["stock"], p.get("description"),
                        p.get("image_file"), "ACTIVE", f"2026-10-{1 + pid % 28:02d} 09:00:00"]))
        table, cols = DETAIL_COLUMNS[cat[4]]
        out.append(row(table, ["product_id"] + cols, [pid] + [p["detail"].get(k) for k in cols]))
        by_cat.setdefault(p["category_slug"], []).append((pid, p))
    for c in CUSTOMERS:
        out.append(row("customer", ["customer_id", "first_name", "middle_name", "last_name", "email", "phone",
                                    "date_of_birth", "password_hash", "created_at"],
                       list(c) + [pbkdf2(PASSWORD, c[4]), "2026-09-01 08:00:00"]))
    for a in ADDRESSES:
        out.append(row("address", ["address_id", "customer_id", "recipient_name", "phone", "house_number", "street",
                                   "district", "city", "is_default"], a))
    for v in VIP:
        out.append(row("customer_vip", ["customer_id", "vip_level", "discount_rate", "reward_points"], v))
    for n in NEW:
        out.append(row("customer_new", ["customer_id", "registered_date", "welcome_voucher"], n))
    for s in STAFF:
        out.append(row("staff", ["staff_id", "full_name", "email", "password_hash", "role"],
                       [s[0], s[1], s[2], pbkdf2(PASSWORD, s[2]), s[3]]))

    def pick(slug, i=0):
        pid, p = by_cat[slug][i % len(by_cat[slug])]
        return pid, p["name"], p["price"]

    rates = {1: "0.05", 2: "0", 3: "0"}
    names = {c[0]: f"{c[3]} {c[2]} {c[1]}" for c in CUSTOMERS}
    # order id, customer, address, date, method, final status, lines [(slug, index, qty)], carrier/tracking
    orders = [
        (1, 3, 4, "2026-10-24 10:12:00", "COD", "DELIVERED", [("fiction", 0, 1), ("business", 0, 1)], ("GHN", "GHN8820417365")),
        (2, 1, 1, "2026-11-08 20:41:00", "CARD", "SHIPPED", [("laptops", 0, 1)], ("Viettel Post", "VTP550193884")),
        (3, 2, 3, "2026-11-10 14:05:00", "COD", "PLACED", [("clothing", 0, 2), ("shoes", 0, 1)], None),
        (4, 3, 4, "2026-11-10 21:30:00", "CARD", "PAID", [("smartphones", 0, 1)], None),
    ]
    staff_name = STAFF[0][1]
    event_id = payment_id = shipping_id = 0
    for oid, cid, aid, date, method, final, spec, ship in orders:
        lines = [pick(slug, i) + (q,) for slug, i, q in spec]
        lines = [(pid, name, q, price) for pid, name, price, q in lines]
        sub, disc, fee, total = totals(lines, rates[cid])
        out.append(row("customer_order", ["order_id", "customer_id", "address_id", "order_date", "status", "payment_method",
                                          "subtotal", "discount", "shipping_fee", "total_amount"],
                       [oid, cid, aid, date, final, method, sub, disc, fee, total]))
        for k, (pid, name, q, price) in enumerate(lines, start=1):
            out.append(row("order_item", ["order_id", "product_id", "product_name", "quantity", "unit_price"],
                           [oid, pid, name, q, price]))
        day = date[:10]
        steps = [("PENDING_PAYMENT" if method == "CARD" else "PLACED", date, names[cid],
                  "Order placed, waiting for card payment" if method == "CARD" else "Order placed, cash on delivery")]
        if method == "CARD":
            steps.append(("PAID", date[:-2] + "55", "Payment provider", "Paid by card ending 4242"))
        flow = ["PROCESSING", "SHIPPED", "DELIVERED"]
        target = flow.index(final) + 1 if final in flow else 0
        when = {"PROCESSING": " 08:30:00", "SHIPPED": " 15:10:00", "DELIVERED": " 11:45:00"}
        offset = {"PROCESSING": 1, "SHIPPED": 1, "DELIVERED": 3}
        for st in flow[:target]:
            d = f"{day[:8]}{int(day[8:]) + offset[st]:02d}{when[st]}"
            note = {"PROCESSING": "Packing started", "SHIPPED": f"Handed to {ship[0]}, tracking {ship[1]}" if ship else "",
                    "DELIVERED": "Delivered to the customer"}[st]
            steps.append((st, d, staff_name, note))
        for st, d, actor, note in steps:
            event_id += 1
            out.append(row("order_event", ["event_id", "order_id", "status", "occurred_at", "actor", "note"],
                           [event_id, oid, st, d, actor, note]))
        if method == "CARD":
            payment_id += 1
            out.append(row("payment", ["payment_id", "order_id", "method", "amount", "status", "payment_date"],
                           [payment_id, oid, "CARD", total, "APPROVED", date[:-2] + "55"]))
            out.append(row("pay_credit", ["payment_id", "card_holder", "card_last4", "expiry", "provider_token"],
                           [payment_id, names[cid].upper(), "4242", "08/28", f"tok_seed{oid:04d}"]))
        if ship and target >= 2:
            shipping_id += 1
            shipped = [s for s in steps if s[0] == "SHIPPED"][0][1]
            delivered = [s for s in steps if s[0] == "DELIVERED"]
            out.append(row("shipping", ["shipping_id", "order_id", "address_id", "carrier", "tracking_number", "shipping_fee",
                                        "status", "shipped_date", "delivered_date"],
                           [shipping_id, oid, aid, ship[0], ship[1], fee, "DELIVERED" if delivered else "IN_TRANSIT",
                            shipped, delivered[0][1] if delivered else None]))
            if delivered and method == "COD":
                payment_id += 1
                out.append(row("payment", ["payment_id", "order_id", "method", "amount", "status", "payment_date"],
                               [payment_id, oid, "CASH", total, "COMPLETED", delivered[0][1]]))
                out.append(row("pay_cash", ["payment_id", "cash_received", "change_amount"], [payment_id, total, 0]))
    (HERE / "seed.sql").write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"seed.sql: {len(products)} products, {len(CUSTOMERS)} customers, {len(STAFF)} staff, {len(orders)} orders")


if __name__ == "__main__":
    main()
